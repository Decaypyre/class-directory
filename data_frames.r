x<-data.frame(food = 1:5,
                 price = c(2.5, 3.0, 4.0, 3.5, 2.0),
                 quantity = c(10, 20, 15, 5, 30))
print(x)
print(nrow(x))
print(ncol(x))
# This code creates a data frame `x` with three columns: food, price, and quantity.
# The `food` column contains integers from 1 to 5, `price` contains numeric values,
# and `quantity` contains integers representing the quantity of each food item.